export function applySeedAudioPreset(state: SeedAudioState, preset: SeedAudioPresetBundle): SeedAudioState {
	if (preset.engineId !== SEED_AUDIO_ENGINE_ID) throw new Error('该预设不属于 Seed Audio 1.0');
	if (!preset.checksum.trim()) throw new Error('预设缺少 checksum，不能应用');
	if (!['self_owned', 'authorized', 'test_only'].includes(preset.licenseStatus)) throw new Error('预设素材授权状态无效');
	const request: SeedAudioRequestEnvelope = {
		engine_id: SEED_AUDIO_ENGINE_ID,
		text: preset.promptTemplate,
		input_mode: preset.inputMode,
		input_assets: structuredClone(preset.assets),
		engine_parameters: seedAudioParametersToRequest(preset.engineParameters)
	};
	const restored = seedAudioStateFromRequest(request);
	return { ...state, mode: restored.mode, drafts: { ...state.drafts, [restored.mode]: restored.drafts[restored.mode] } } as SeedAudioState;
}
